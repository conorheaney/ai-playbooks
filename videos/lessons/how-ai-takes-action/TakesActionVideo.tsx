import React from 'react';
import {AbsoluteFill, Easing, interpolate, Sequence, useCurrentFrame} from 'remotion';
import {Background} from '../../shared/components/Background';
import {Stage, trackAt} from '../../shared/components/Stage';
import {FONT} from '../../shared/fonts';
import {COLORS} from '../../shared/theme';
import {SoundTrack} from './audio';
import {CENTERING} from './centering';
import {BoundariesScene} from './scenes/BoundariesScene';
import {ContextScene} from './scenes/ContextScene';
import {DelegationScene} from './scenes/DelegationScene';
import {FailureScene} from './scenes/FailureScene';
import {HarnessScene} from './scenes/HarnessScene';
import {LoopScene} from './scenes/LoopScene';
import {ToolsScene} from './scenes/ToolsScene';
import {WordsScene} from './scenes/WordsScene';
import {WorkflowScene} from './scenes/WorkflowScene';
import {FAILURE, SCENES, TOTAL_FRAMES} from './timing';

export type VideoProps = {
  // SFX are generated by `npm run sfx` into public/sfx.
  sfx: boolean;
  // Plays whichever VO clips exist in public/vo/how-ai-takes-action; see BLUEPRINT.md for file names.
  voiceover: boolean;
  // Shifts content to keep it centred, from the track in centering.ts. Off only for measuring.
  center?: boolean;
};

const SCENE_LIST = [
  ['1 · Words aren\'t actions', 'words', WordsScene],
  ['2 · Tool calling', 'tools', ToolsScene],
  ['3 · Back into context', 'context', ContextScene],
  ['4 · The agent loop', 'loop', LoopScene],
  ['5 · Workflow vs agent', 'workflow', WorkflowScene],
  ['6 · The harness', 'harness', HarnessScene],
  ['7 · Boundaries', 'boundaries', BoundariesScene],
  ['8 · Delegation', 'delegation', DelegationScene],
  ['9 · When tools fail', 'failure', FailureScene],
] as const;

// The cube and the travel portal carry across cuts, so scenes fade their own content rather than the whole frame.
export const TakesActionVideo: React.FC<VideoProps> = ({sfx, voiceover, center = true}) => {
  const frame = useCurrentFrame();
  return (
    <AbsoluteFill style={{backgroundColor: COLORS.charcoal, fontFamily: FONT}}>
      <Background />

      <Stage x={center ? trackAt(CENTERING, frame) : 0}>
        {SCENE_LIST.map(([name, key, Scene]) => (
          <Sequence key={key} name={name} {...SCENES[key]}>
            <Scene />
          </Sequence>
        ))}
      </Stage>

      {/* The video ends with the whole frame fading to black over the last 3 seconds. */}
      <AbsoluteFill
        style={{
          backgroundColor: '#000',
          opacity: interpolate(frame, [SCENES.failure.from + FAILURE.outro, TOTAL_FRAMES], [0, 1], {extrapolateLeft: 'clamp', extrapolateRight: 'clamp', easing: Easing.in(Easing.quad)}),
        }}
      />

      <SoundTrack sfx={sfx} voiceover={voiceover} />
    </AbsoluteFill>
  );
};
