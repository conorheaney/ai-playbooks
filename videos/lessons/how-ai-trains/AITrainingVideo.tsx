import React from 'react';
import {AbsoluteFill, Sequence, useCurrentFrame} from 'remotion';
import {Stage, trackAt} from '../../shared/components/Stage';
import {SoundTrack} from './audio';
import {CENTERING} from './centering';
import {Background} from '../../shared/components/Background';
import {SceneFade} from '../../shared/components/SceneFade';
import {FONT} from '../../shared/fonts';
import {RawDataScene} from './scenes/RawDataScene';
import {TokenizeScene} from './scenes/TokenizeScene';
import {EvalsScene} from './scenes/EvalsScene';
import {FeedbackScene} from './scenes/FeedbackScene';
import {FineTuneScene} from './scenes/FineTuneScene';
import {LockInScene} from './scenes/LockInScene';
import {ReinforceScene} from './scenes/ReinforceScene';
import {ReleaseScene} from './scenes/ReleaseScene';
import {SafetyScene} from './scenes/SafetyScene';
import {WeightsScene} from './scenes/WeightsScene';
import {COLORS} from '../../shared/theme';
import {SCENES} from './timing';

export type VideoProps = {
  // SFX are generated by `npm run sfx` into public/sfx.
  sfx: boolean;
  // Plays whichever VO clips exist in public/vo; see BLUEPRINT.md for file names.
  voiceover: boolean;
  // Shifts content to keep it centred, from the measured track in centering.ts. Off only for measuring.
  center?: boolean;
};

export const AITrainingVideo: React.FC<VideoProps> = ({sfx, voiceover, center = true}) => {
  const frame = useCurrentFrame();
  return (
    <AbsoluteFill style={{backgroundColor: COLORS.charcoal, fontFamily: FONT}}>
      <Background />

      <Stage x={center ? trackAt(CENTERING, frame) : 0}>
        <Sequence name="1 · Raw Data" {...SCENES.rawData}>
          <SceneFade durationInFrames={SCENES.rawData.durationInFrames} fadeIn={0}>
            <RawDataScene />
          </SceneFade>
        </Sequence>

        <Sequence name="2 · Tokenize & Map" {...SCENES.tokenize}>
          <SceneFade durationInFrames={SCENES.tokenize.durationInFrames}>
            <TokenizeScene />
          </SceneFade>
        </Sequence>

        {/* No fade out: the network hands off directly to Scene 4's collapse. */}
        <Sequence name="3 · Adjusting Weights" {...SCENES.weights}>
          <SceneFade durationInFrames={SCENES.weights.durationInFrames} fadeOut={0}>
            <WeightsScene />
          </SceneFade>
        </Sequence>

        {/* Post-training: the model cube carries across scenes, so these scenes fade their own content, not the cube. */}
        {(
          [
            ['4 · Fine-tune', 'fineTune', FineTuneScene],
            ['5 · Feedback', 'feedback', FeedbackScene],
            ['6 · Reinforcement learning', 'reinforce', ReinforceScene],
            ['7 · Safety', 'safety', SafetyScene],
            ['8 · Evaluation', 'evals', EvalsScene],
            ['9 · Locked in', 'lockIn', LockInScene],
            ['10 · Release', 'release', ReleaseScene],
          ] as const
        ).map(([name, key, Scene]) => (
          <Sequence key={key} name={name} {...SCENES[key]}>
            <Scene />
          </Sequence>
        ))}
      </Stage>

      <SoundTrack sfx={sfx} voiceover={voiceover} />
    </AbsoluteFill>
  );
};
