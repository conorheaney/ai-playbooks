import React from 'react';
import {AbsoluteFill, Sequence, useCurrentFrame} from 'remotion';
import {Background} from '../../shared/components/Background';
import {SceneFade} from '../../shared/components/SceneFade';
import {Stage, trackAt} from '../../shared/components/Stage';
import {FONT} from '../../shared/fonts';
import {COLORS} from '../../shared/theme';
import {SoundTrack} from './audio';
import {CENTERING} from './centering';
import {AssembleScene} from './scenes/AssembleScene';
import {CompactionScene} from './scenes/CompactionScene';
import {MiddleScene} from './scenes/MiddleScene';
import {SettingsScene} from './scenes/SettingsScene';
import {StoppingScene} from './scenes/StoppingScene';
import {TemporaryScene} from './scenes/TemporaryScene';
import {TokensScene} from './scenes/TokensScene';
import {WindowScene} from './scenes/WindowScene';
import {SCENES} from './timing';

export type VideoProps = {
  // SFX are generated by `npm run sfx` into public/sfx.
  sfx: boolean;
  // Plays whichever VO clips exist in public/vo/how-ai-responds; see BLUEPRINT.md for file names.
  voiceover: boolean;
  // Shifts content to keep it centred, from the measured track in centering.ts. Off only for measuring.
  center?: boolean;
};

const SCENE_LIST = [
  ['2 · Context window', 'window', WindowScene],
  ['3 · One token at a time', 'tokens', TokensScene],
  ['4 · Same prompt, different answers', 'settings', SettingsScene],
  ['5 · Lost in the middle', 'middle', MiddleScene],
  ['6 · Compaction', 'compaction', CompactionScene],
  ['7 · Stopping', 'stopping', StoppingScene],
  ['8 · Context is temporary', 'temporary', TemporaryScene],
] as const;

// The model cube and the context window carry across cuts, so scenes fade their own content
// rather than the whole frame. Only Scene 1 fades in from black.
export const AIRespondsVideo: React.FC<VideoProps> = ({sfx, voiceover, center = true}) => {
  const frame = useCurrentFrame();
  return (
    <AbsoluteFill style={{backgroundColor: COLORS.charcoal, fontFamily: FONT}}>
      <Background />

      <Stage x={center ? trackAt(CENTERING, frame) : 0}>
        <Sequence name="1 · Assemble the context" {...SCENES.assemble}>
          <SceneFade durationInFrames={SCENES.assemble.durationInFrames} fadeIn={0} fadeOut={0}>
            <AssembleScene />
          </SceneFade>
        </Sequence>

        {SCENE_LIST.map(([name, key, Scene]) => (
          <Sequence key={key} name={name} {...SCENES[key]}>
            <Scene />
          </Sequence>
        ))}
      </Stage>

      <SoundTrack sfx={sfx} voiceover={voiceover} />
    </AbsoluteFill>
  );
};
