import React from 'react';
import {AbsoluteFill, Sequence, useCurrentFrame} from 'remotion';
import {Background} from '../../shared/components/Background';
import {SceneFade} from '../../shared/components/SceneFade';
import {Stage, trackAt} from '../../shared/components/Stage';
import {FONT} from '../../shared/fonts';
import {COLORS} from '../../shared/theme';
import {SoundTrack} from './audio';
import {CENTERING} from './centering';
import {AskScene} from './scenes/AskScene';
import {CitationsScene} from './scenes/CitationsScene';
import {EngineeringScene} from './scenes/EngineeringScene';
import {MemoryScene} from './scenes/MemoryScene';
import {PrepareScene} from './scenes/PrepareScene';
import {PromptScene} from './scenes/PromptScene';
import {SpecificScene} from './scenes/SpecificScene';
import {WeightsScene} from './scenes/WeightsScene';
import {SCENES} from './timing';

export type VideoProps = {
  // SFX are generated by `npm run sfx` into public/sfx.
  sfx: boolean;
  // Plays whichever VO clips exist in public/vo/how-ai-gets-context; see BLUEPRINT.md for file names.
  voiceover: boolean;
  // Shifts content to keep it centred, from the measured track in centering.ts. Off only for measuring.
  center?: boolean;
};

const SCENE_LIST = [
  ['2 · The prompt', 'prompt', PromptScene],
  ['3 · Vague vs specific', 'specific', SpecificScene],
  ['4 · Context engineering', 'engineering', EngineeringScene],
  ['5 · Retrieval: prepare', 'prepare', PrepareScene],
  ['6 · Retrieval: ask', 'ask', AskScene],
  ['7 · Check the source', 'citations', CitationsScene],
  ['8 · Memory', 'memory', MemoryScene],
] as const;

// The model cube and the context window carry across cuts, so scenes fade their own content
// rather than the whole frame. Only Scene 1 fades in from black.
export const AIContextVideo: React.FC<VideoProps> = ({sfx, voiceover, center = true}) => {
  const frame = useCurrentFrame();
  return (
    <AbsoluteFill style={{backgroundColor: COLORS.charcoal, fontFamily: FONT}}>
      <Background />

      <Stage x={center ? trackAt(CENTERING, frame) : 0}>
        <Sequence name="1 · Beyond the weights" {...SCENES.weights}>
          <SceneFade durationInFrames={SCENES.weights.durationInFrames} fadeIn={0} fadeOut={0}>
            <WeightsScene />
          </SceneFade>
        </Sequence>

        {SCENE_LIST.map(([name, key, Scene]) => (
          <Sequence key={key} name={name} {...SCENES[key]}>
            <Scene />
          </Sequence>
        ))}
      </Stage>

      <SoundTrack sfx={sfx} voiceover={voiceover} />
    </AbsoluteFill>
  );
};
